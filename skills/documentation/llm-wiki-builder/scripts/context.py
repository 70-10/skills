"""Build the index of an LLM wiki bundle and audit its pages against schema.yaml.

The bundle is the directory that holds schema.yaml. This file normally lives in
<bundle>/tools/, so --root defaults to the parent of this file's directory.

  uv run <bundle>/tools/context.py index            rewrite <bundle>/index.md
  uv run <bundle>/tools/context.py audit [--report] exit 1 on FAIL, 2 on a broken schema
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import sys
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path
from urllib.parse import unquote, urlsplit

import yaml

INDEX_MARK = "<!-- generated by tools/context.py index. Do not edit. -->"

SCHEMA_KEYS = {
    "kind", "title", "description", "dirs", "collections", "common", "types", "enums",
    "date_keys", "person_keys", "people", "filename", "inflows", "deferred", "source_kinds",
    "max_body_lines",
}
SCHEMA_REQUIRED = {"kind", "title", "description", "dirs", "common"}
NESTED_KEYS = {
    "common": {"required", "optional"},
    "dirs": {"types", "protocol"},
    "collections": {"type"},
    "types": {"required", "optional", "sections", "enums"},
}
TOP_LISTS = ("date_keys", "person_keys", "inflows", "deferred", "source_kinds")
LINK = re.compile(r"\[[^\]]*\]\(([^)\s]+)\)")
FRONTMATTER = re.compile(r"\A---\n(.*?)\n---\n?(.*)\Z", re.DOTALL)
FENCED_CODE = re.compile(r"^(```|~~~).*?^\1", re.DOTALL | re.MULTILINE)
INLINE_CODE = re.compile(r"`[^`\n]*`")
HUMAN = "human:"


class SchemaError(Exception):
    pass


class _Loader(yaml.SafeLoader):
    pass


# Dates stay strings so that a wrong date becomes a "date" finding, not an unreadable frontmatter.
_Loader.yaml_implicit_resolvers = {
    k: [(tag, rx) for tag, rx in v if tag != "tag:yaml.org,2002:timestamp"]
    for k, v in yaml.SafeLoader.yaml_implicit_resolvers.items()
}


@dataclass(frozen=True, order=True)
class Finding:
    level: str
    path: str
    code: str
    message: str


@dataclass
class Page:
    rel: str
    path: Path
    meta: dict | None
    body: str
    error: str | None = None


@dataclass
class Bundle:
    root: Path
    schema: dict
    pages: list[Page]

    @property
    def repo(self) -> Path:
        return self.root.parent


# ---- loading


def load_schema(root: Path) -> dict:
    path = root / "schema.yaml"
    try:
        schema = yaml.load(path.read_text(encoding="utf-8"), Loader=_Loader)
    except (OSError, yaml.YAMLError) as exc:
        raise SchemaError(f"{path}: {exc}") from exc
    if not isinstance(schema, dict):
        raise SchemaError(f"{path}: not a mapping")
    unknown = set(schema) - SCHEMA_KEYS
    if unknown:
        raise SchemaError(f"{path}: unknown keys {sorted(unknown)}")
    missing = SCHEMA_REQUIRED - set(schema)
    if missing:
        raise SchemaError(f"{path}: missing keys {sorted(missing)}")

    for section in ("dirs", "types", "collections", "common", "enums"):
        if section in schema and not isinstance(schema[section], dict):
            raise SchemaError(f"{path}: {section} must be a mapping")

    string_lists = [(k, schema[k]) for k in TOP_LISTS if k in schema]
    enum_lists = [(f"enums.{k}", v) for k, v in (schema.get("enums") or {}).items()]
    specs = [("common", "", schema.get("common") or {})]
    specs += [(section, f".{name}", spec) for section in ("dirs", "collections", "types")
              for name, spec in (schema.get(section) or {}).items()]
    for section, name, spec in specs:
        where = f"{section}{name}"
        if not isinstance(spec, dict):
            raise SchemaError(f"{path}: {where} is not a mapping")
        unknown = set(spec) - NESTED_KEYS[section]
        if unknown:
            raise SchemaError(f"{path}: {where} has unknown keys {sorted(unknown)}")
        string_lists += [(f"{where}.{k}", v) for k, v in spec.items() if k not in ("protocol", "type", "enums")]
        if "enums" in spec and not isinstance(spec["enums"], dict):
            raise SchemaError(f"{path}: {where}.enums must be a mapping")
        enum_lists += [(f"{where}.enums.{k}", v) for k, v in spec.get("enums", {}).items()]
        if section == "dirs" and not spec.get("types"):
            raise SchemaError(f"{path}: {where} needs types")
    for where, value in string_lists + enum_lists:
        if not isinstance(value, list):
            raise SchemaError(f"{path}: {where} must be a list, like [a, b]")
    for where, value in string_lists:
        if not all(isinstance(item, str) for item in value):
            raise SchemaError(f"{path}: {where} must contain strings")
    if schema.get("person_keys") and not schema.get("people"):
        raise SchemaError(f"{path}: person_keys needs people (the collection that lists the ids)")
    if "filename" in schema:
        try:
            re.compile(schema["filename"])
        except (TypeError, re.error) as exc:
            raise SchemaError(f"{path}: invalid filename regex: {exc}") from exc
    if "max_body_lines" in schema:
        limit = schema["max_body_lines"]
        if type(limit) is not int or limit < 0:
            raise SchemaError(f"{path}: max_body_lines must be a nonnegative integer")
    return schema


def _parse(text: str) -> tuple[dict | None, str, str | None]:
    m = FRONTMATTER.match(text)
    if not m:
        return None, text, "no frontmatter between --- lines"
    try:
        meta = yaml.load(m.group(1), Loader=_Loader)
    except yaml.YAMLError as exc:
        return None, m.group(2), f"YAML error: {exc}"
    if not isinstance(meta, dict):
        return None, m.group(2), "frontmatter is not a mapping"
    return meta, m.group(2), None


def load_pages(root: Path) -> list[Page]:
    pages = []
    for path in sorted(root.rglob("*.md")):
        rel = path.relative_to(root).as_posix()
        if rel == "index.md" or rel.startswith("tools/"):
            continue
        meta, body, error = _parse(path.read_text(encoding="utf-8"))
        pages.append(Page(rel, path.resolve(), meta, body, error))
    return pages


def load(root: Path) -> Bundle:
    root = root.resolve()
    return Bundle(root, load_schema(root), load_pages(root))


# ---- references


def _is_url(target: str) -> bool:
    return bool(urlsplit(target).scheme)


def _resolve(repo: Path, base: Path, raw: str) -> Path | None:
    """Turn a link or a path into a file path. A leading / starts at the repository root, the same as on GitHub."""
    if not raw or _is_url(raw) or raw.startswith("#") or "<" in raw:
        return None
    target = unquote(raw.split("#", 1)[0])
    if target.startswith("/"):
        return (repo / target.lstrip("/")).resolve()
    return (base / target).resolve()


def _page_links(page: Page) -> list[str]:
    prose = INLINE_CODE.sub("", FENCED_CODE.sub("", page.body))
    return LINK.findall(prose) + [str(t) for t in _as_list((page.meta or {}).get("related")) if t]


def _as_list(value) -> list:
    if value is None:
        return []
    return value if isinstance(value, list) else [value]


def _valid_date(value) -> bool:
    if not isinstance(value, str) or not re.fullmatch(r"\d{4}-\d{2}-\d{2}", value):
        return False
    try:
        dt.date.fromisoformat(value)
    except ValueError:
        return False
    return True


def _person_id(value) -> str | None:
    if isinstance(value, str) and value.startswith(HUMAN):
        return value[len(HUMAN):]
    return None


def _is_verified(value) -> bool:
    return isinstance(value, dict) and _person_id(value.get("by")) is not None and _valid_date(value.get("at"))


# ---- index


def _cell(value) -> str:
    if value is None:
        return ""
    if isinstance(value, list):
        value = ", ".join(str(v) for v in value)
    return str(value).replace("|", "\\|").replace("\n", " ")


def build_index(bundle: Bundle) -> str:
    schema = bundle.schema
    lines = [INDEX_MARK, "", f"# {schema['title']}", "", str(schema["description"]).strip(), "",
             "| path | type | title | aliases | description |", "|---|---|---|---|---|"]
    for p in bundle.pages:
        meta = p.meta or {}
        lines.append(f"| [{p.rel}]({p.rel}) | {_cell(meta.get('type'))} | {_cell(meta.get('title'))} "
                     f"| {_cell(meta.get('aliases'))} | {_cell(meta.get('description'))} |")
    return "\n".join(lines) + "\n"


# ---- audit


@dataclass
class _Rules:
    """Per-type values from schema.yaml, built once instead of once per page."""
    required: list[str]
    allowed: set[str]
    enums: dict[str, list]
    sections: list[tuple[str, re.Pattern]]


@dataclass
class _Run:
    bundle: Bundle
    today: dt.date
    rules: dict
    people: set[str]
    by_path: dict[Path, Page]
    found: list[Finding] = field(default_factory=list)
    linked: set[Path] = field(default_factory=set)
    cited: set[Path] = field(default_factory=set)
    exists: dict[Path, bool] = field(default_factory=dict)

    def fail(self, path: str, code: str, msg: str) -> None:
        self.found.append(Finding("FAIL", path, code, msg))

    def warn(self, path: str, code: str, msg: str) -> None:
        self.found.append(Finding("WARN", path, code, msg))

    def is_file(self, path: Path) -> bool:
        if path in self.by_path:
            return True
        if path not in self.exists:
            self.exists[path] = path.exists()
        return self.exists[path]


def _rules(schema: dict) -> dict:
    common = schema.get("common") or {}
    out = {}
    for name, spec in {None: {}, **(schema.get("types") or {})}.items():
        required = list(common.get("required") or []) + list(spec.get("required") or [])
        out[name] = _Rules(
            required=required,
            allowed=set(required) | set(common.get("optional") or []) | set(spec.get("optional") or []),
            enums={**(schema.get("enums") or {}), **(spec.get("enums") or {})},
            sections=[(s, re.compile(rf"^## {re.escape(s)}\s*$", re.MULTILINE)) for s in spec.get("sections") or []],
        )
    return out


def _people_ids(bundle: Bundle) -> set[str]:
    rel = bundle.schema.get("people")
    page = next((p for p in bundle.pages if p.rel == rel), None)
    if page is None:
        return set()
    return {m.group(1) for m in re.finditer(r"^## (\S+)", page.body, flags=re.MULTILINE)}


def _points_back(run: _Run, page: Page, target: str, back_key: str) -> bool:
    repo = run.bundle.repo
    other = run.by_path.get(_resolve(repo, page.path.parent, target))
    back = (other.meta or {}).get(back_key) if other else None
    return bool(back) and _resolve(repo, other.path.parent, str(back)) == page.path


def _check_page(run: _Run, p: Page) -> None:
    schema = run.bundle.schema
    meta = p.meta
    ptype = meta.get("type")
    if not isinstance(ptype, str):
        run.fail(p.rel, "unknown-type", "type must be a string")
        ptype = None
    rules = run.rules.get(ptype, run.rules[None])
    collections = schema.get("collections") or {}
    dirs = schema["dirs"]

    if schema.get("filename") and not re.match(schema["filename"], p.path.name):
        run.fail(p.rel, "filename", f"{p.path.name} does not match {schema['filename']}")

    if p.rel in collections:
        want = collections[p.rel].get("type")
        if ptype != want:
            run.fail(p.rel, "unknown-type", f"type {ptype!r}; this collection holds {want!r}")
    else:
        top = p.rel.split("/", 1)[0] if "/" in p.rel else None
        if top not in dirs:
            run.fail(p.rel, "unknown-dir", "the page is not in a directory that schema.yaml lists")
        elif ptype not in dirs[top]["types"]:
            run.fail(p.rel, "unknown-type", f"type {ptype!r} is not one of {dirs[top]['types']}")

    for key in rules.required:
        if meta.get(key) in (None, "", []):
            run.fail(p.rel, "missing-key", f"required key {key!r} is missing or empty")
    for key in meta:
        if key not in rules.allowed:
            run.fail(p.rel, "unknown-key", f"key {key!r} is not in schema.yaml")
    for key, values in rules.enums.items():
        for v in _as_list(meta.get(key)):
            if v not in values:
                run.fail(p.rel, "enum", f"{key}: {v!r} is not one of {values}")
    for key in schema.get("date_keys") or []:
        if key in meta and not _valid_date(meta[key]):
            run.fail(p.rel, "date", f"{key}: {meta[key]!r} is not a YYYY-MM-DD date")

    persons = [v for k in schema.get("person_keys") or [] for v in _as_list(meta.get(k))]
    if "verified" in meta:
        if _is_verified(meta["verified"]):
            persons.append(meta["verified"]["by"])
        else:
            run.fail(p.rel, "verified", "verified must be {by: human:<id>, at: YYYY-MM-DD}")
    for v in persons:
        pid = _person_id(v)
        if pid is None:
            run.fail(p.rel, "unknown-person", f"{v!r} must be written as {HUMAN}<id>")
        elif schema.get("people") and pid not in run.people:
            run.fail(p.rel, "unknown-person", f"{v} is not a '## <id>' heading in {schema['people']}")

    for name, heading in rules.sections:
        if not heading.search(p.body):
            run.fail(p.rel, "missing-section", f"section '## {name}' is missing")

    repo = run.bundle.repo
    for raw in _page_links(p):
        target = _resolve(repo, p.path.parent, raw)
        if target is None:
            continue
        if not run.is_file(target):
            run.fail(p.rel, "broken-link", f"link to {raw} does not exist")
        run.linked.add(target)
    source_kinds = schema.get("source_kinds") or []
    for src in _as_list(meta.get("sources")):
        if not isinstance(src, dict) or any(
            not isinstance(src.get(key), str) or not src[key].strip()
            for key in ("kind", "resource")
        ):
            run.fail(p.rel, "source", "each source must have nonempty string kind and resource values")
            continue
        target = _resolve(repo, repo, src["resource"].lstrip("/"))
        if target is not None:
            if not run.is_file(target):
                run.fail(p.rel, "broken-link", f"sources[].resource {src['resource']} does not exist")
            run.cited.add(target)
        if source_kinds and src.get("kind") not in source_kinds:
            run.fail(p.rel, "enum", f"sources[].kind: {src.get('kind')!r} is not one of {source_kinds}")

    if meta.get("status") == "superseded" and not meta.get("superseded_by"):
        run.fail(p.rel, "supersede", "superseded status requires a superseded_by reference")
    if meta.get("superseded_by") and meta.get("status") != "superseded":
        run.fail(p.rel, "supersede", "superseded_by is set but status is not 'superseded'")
    for key, back_key in (("superseded_by", "supersedes"), ("supersedes", "superseded_by")):
        target = meta.get(key)
        if target and not _points_back(run, p, str(target), back_key):
            run.fail(p.rel, "supersede", f"{key}: {target} must exist and point back with '{back_key}'")

    stale = meta.get("stale_after")
    if _valid_date(stale) and dt.date.fromisoformat(stale) < run.today:
        run.warn(p.rel, "stale", f"stale_after {stale} has passed")
    max_body = schema.get("max_body_lines")
    if max_body and len(p.body.strip().splitlines()) > max_body:
        run.warn(p.rel, "long-body", f"the body is longer than {max_body} lines")


def audit(bundle: Bundle, today: dt.date | None = None) -> list[Finding]:
    schema = bundle.schema
    collections = schema.get("collections") or {}
    run = _Run(bundle, today or dt.date.today(), _rules(schema), _people_ids(bundle),
               {p.path: p for p in bundle.pages})

    for p in bundle.pages:
        if p.meta is None:
            run.fail(p.rel, "frontmatter", p.error or "unreadable")
        else:
            _check_page(run, p)

    for p in bundle.pages:
        if p.meta is not None and p.rel not in collections and p.path not in run.linked:
            run.warn(p.rel, "orphan", "no other page links to this page")

    names: dict[str, set[str]] = {}
    for p in bundle.pages:
        for name in [(p.meta or {}).get("title"), *_as_list((p.meta or {}).get("aliases"))]:
            if name:
                names.setdefault(str(name).casefold(), set()).add(p.rel)
    for name, rels in names.items():
        if len(rels) > 1:
            for rel in sorted(rels):
                run.fail(rel, "alias-conflict", f"the name {name!r} also names {sorted(rels - {rel})}")

    repo = bundle.repo
    referenced = run.linked | run.cited
    deferred = {f.resolve() for pattern in schema.get("deferred") or [] for f in repo.glob(pattern)}
    for pattern in schema.get("inflows") or []:
        for f in sorted(repo.glob(pattern)):
            resolved = f.resolve()
            if resolved in referenced:
                continue
            rel = f.relative_to(repo).as_posix()
            if resolved in deferred:
                run.warn(rel, "deferred", "listed in deferred; not taken in yet")
            else:
                run.fail(rel, "inflow", "no page cites this file in sources or links to it")

    index = bundle.root / "index.md"
    if not index.is_file() or index.read_text(encoding="utf-8") != build_index(bundle):
        run.fail("index.md", "index", "index.md is out of date; run the index command")

    return sorted(set(run.found))


def report(bundle: Bundle) -> dict:
    metas = [p.meta or {} for p in bundle.pages]
    return {
        "counts": dict(sorted(Counter(str(m.get("type")) for m in metas).items())),
        "unverified": [p.rel for p, m in zip(bundle.pages, metas) if not _is_verified(m.get("verified"))],
        "superseded": [p.rel for p, m in zip(bundle.pages, metas) if m.get("status") == "superseded"],
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent,
                        help="the bundle directory that holds schema.yaml")
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("index", help="rewrite index.md")
    a = sub.add_parser("audit", help="check every page against schema.yaml")
    a.add_argument("--report", action="store_true", help="also print counts and unverified pages as JSON")
    args = parser.parse_args(argv)
    try:
        bundle = load(args.root)
    except SchemaError as exc:
        print(f"schema error: {exc}", file=sys.stderr)
        return 2
    if args.command == "index":
        (bundle.root / "index.md").write_text(build_index(bundle), encoding="utf-8")
        print(f"wrote {bundle.root / 'index.md'}")
        return 0
    findings = audit(bundle)
    for f in findings:
        print(f"{f.level}  {f.path}  {f.code}  {f.message}")
    fails = sum(f.level == "FAIL" for f in findings)
    print(f"FAIL {fails} · WARN {len(findings) - fails}")
    if args.report:
        print(json.dumps(report(bundle), ensure_ascii=False, indent=2))
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
